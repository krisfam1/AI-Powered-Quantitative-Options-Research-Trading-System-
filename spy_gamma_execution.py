def check_and_enter_spy_gamma() -> dict:
    signal = check_spy_gamma_signal()
    if not signal["signal_fired"]:
        return signal

    ticker = signal["ticker"]
    option_type = signal["option_type"]
    current_price = signal["current_price"]

    breaker_check = check_ticker_circuit_breaker(ticker)
    if breaker_check["blocked"]:
        return {"signal_fired": True, "executed": False, "note": "circuit breaker: " + breaker_check["reason"]}

    cooldown_minutes = 90
    with _sqlite3.connect("options_signal_log.db") as _con:
        try:
            _row = _con.execute(
                "SELECT checked_at FROM options_signal_log WHERE ticker = ? AND signal_fired = 1 ORDER BY checked_at DESC LIMIT 1",
                ("SPY-GAMMA",),
            ).fetchone()
        except Exception:
            _row = None
    if _row:
        _last_fired = datetime.fromisoformat(_row[0])
        _minutes_since = (datetime.now(timezone.utc) - _last_fired).total_seconds() / 60
        if _minutes_since < cooldown_minutes:
            return {"signal_fired": True, "executed": False, "note": "cooldown active -- fired " + str(round(_minutes_since, 0)) + " min ago"}

    account = _trading_client.get_account()
    equity = float(account.equity)
    last_equity = float(account.last_equity) if account.last_equity else equity
    daily_pnl_frac = (equity - last_equity) / last_equity if last_equity else 0.0

    peak_file = Path(".options_peak_equity")
    if peak_file.exists():
        try:
            stored_peak = float(peak_file.read_text().strip())
            peak_equity = max(stored_peak, equity)
        except ValueError:
            peak_equity = equity
    else:
        peak_equity = equity
    rolling_pnl_frac = (equity - peak_equity) / peak_equity if peak_equity else 0.0

    if not check_daily_loss_limit(daily_pnl_frac):
        return {"signal_fired": True, "executed": False, "note": "daily loss limit hit (" + str(round(daily_pnl_frac*100, 2)) + "% today)"}
    if not check_drawdown_pause(rolling_pnl_frac):
        return {"signal_fired": True, "executed": False, "note": "drawdown pause triggered (" + str(round(rolling_pnl_frac*100, 2)) + "% from peak)"}

    positions = _trading_client.get_all_positions()
    options_positions = [p for p in positions if getattr(p, "asset_class", None) is not None and "option" in str(p.asset_class).lower()]
    if not check_max_positions(len(options_positions)):
        return {"signal_fired": True, "executed": False, "note": "max options positions reached (" + str(len(options_positions)) + " open, account-wide)"}

    try:
        chain = get_options_chain(ticker, option_type)
        near_money = filter_near_the_money(chain, current_price)
        best = pick_best_contract(near_money)
        if best is None:
            return {"signal_fired": True, "executed": False, "note": "no suitable contract found"}
    except Exception as exc:
        return {"signal_fired": True, "executed": False, "note": "contract selection failed: " + str(exc)}

    try:
        premium = get_live_premium(best.symbol)
    except Exception as exc:
        return {"signal_fired": True, "executed": False, "note": "premium fetch failed: " + str(exc)}

    account = _trading_client.get_account()
    equity = float(account.equity)
    max_risk_dollars = equity * POSITION_RISK_PCT
    contracts = max(int(max_risk_dollars / (premium * 100)), 1)

    with _sqlite3.connect("options_signal_log.db") as _con:
        try:
            _con.execute(
                "CREATE TABLE IF NOT EXISTS options_signal_log (id INTEGER PRIMARY KEY AUTOINCREMENT, ticker TEXT, signal_fired INTEGER, checked_at TEXT, note TEXT)"
            )
            _con.execute(
                "INSERT INTO options_signal_log (ticker, signal_fired, checked_at, note) VALUES (?, ?, ?, ?)",
                ("SPY-GAMMA", 1, datetime.now(timezone.utc).isoformat(), signal["note"]),
            )
            _con.commit()
        except Exception:
            pass

    if spy_gamma_daytrader.SPY_GAMMA_SHADOW_MODE:
        _tranches_preview = _build_tranches(contracts)
        note = "SHADOW MODE -- would buy " + str(contracts) + "x " + best.symbol + " @ ~$" + str(round(premium, 2)) + " split into tranches " + str(_tranches_preview) + " | " + signal["note"]
        return {"signal_fired": True, "executed": False, "note": note}

    order_request = OptMarketOrderRequest(
        symbol=best.symbol, qty=contracts, side=OptOrderSide.BUY, time_in_force=OptTimeInForce.DAY,
    )
    order = _trading_client.submit_order(order_request)

    real_entry_premium = premium
    for _ in range(10):
        time.sleep(1)
        try:
            refreshed = _trading_client.get_order_by_id(order.id)
            if refreshed.filled_avg_price:
                real_entry_premium = float(refreshed.filled_avg_price)
                break
        except Exception:
            continue

    # Split into scale-out tranches: A (40% target), B (75% target),
    # RUNNER (reversal_guard, looser 50% threshold, no fixed cap).
    # Each tranche is logged as its own trade for independent tracking.
    tranche_plan = _build_tranches(contracts)
    trade_ids = []
    for tranche_name, tranche_contracts in tranche_plan.items():
        if tranche_contracts <= 0:
            continue
        trade_id = "spy-gamma-" + tranche_name + "-" + str(order.id)
        if tranche_name == "A":
            _tp, _sl = 0.20, STOP_LOSS_PCT
        elif tranche_name == "B":
            _tp, _sl = 0.40, STOP_LOSS_PCT
        elif tranche_name == "C":
            _tp, _sl = 0.75, STOP_LOSS_PCT
        else:  # RUNNER
            _tp, _sl = 999.0, STOP_LOSS_PCT  # no fixed cap -- reversal_guard handles the exit
        _gamma_context = {
            "regime": signal.get("regime"),
            "wall_price": signal.get("wall_price"),
            "current_price_at_entry": current_price,
            "confluence_bonuses": signal.get("confluence_bonuses", []),
            "tranche": tranche_name,
        }
        try:
            from datetime import date as _date
            from feature_extraction import extract_features_live
            _dte_for_features = (best.expiration_date - _date.today()).days
            _full_features = extract_features_live(ticker, option_type, best.strike_price, _dte_for_features)
            _gamma_context.update(_full_features)
        except Exception:
            pass
        options_trade_log.log_entry({
            "trade_id": trade_id,
            "ticker": ticker,
            "contract_symbol": best.symbol,
            "option_type": option_type,
            "entry_date": datetime.now(timezone.utc).date().isoformat(),
            "entry_premium": real_entry_premium,
            "contracts": tranche_contracts,
            "stop_loss_pct": _sl,
            "take_profit_pct": _tp,
            "expiry_date": best.expiration_date.isoformat(),
            "gamma_context": json.dumps(_gamma_context),
        })
        trade_ids.append(trade_id)

    return {"signal_fired": True, "executed": True, "trade_ids": trade_ids, "note": "LIVE order placed: " + str(contracts) + "x " + best.symbol + " @ $" + str(real_entry_premium) + " split into tranches " + str(tranche_plan)}


def _build_tranches(total_contracts: int) -> dict:
    """
    Split total contracts into 4 scale-out tranches: A (~20%, 20% target),
    B (~20%, 40% target), C (~20%, 75% target), RUNNER (~40%,
    reversal_guard, no fixed cap). Falls back to a single RUNNER-only
    position if too few contracts to meaningfully split (fewer than 6).
    """
    if total_contracts < 6:
        return {"A": 0, "B": 0, "C": 0, "RUNNER": total_contracts}

    a = max(int(total_contracts * 0.20), 1)
    b = max(int(total_contracts * 0.20), 1)
    c = max(int(total_contracts * 0.20), 1)
    runner = total_contracts - a - b - c
    return {"A": a, "B": b, "C": c, "RUNNER": runner}


def check_and_close_spy_gamma_positions() -> int:
    open_positions = [p for p in options_trade_log.get_open_positions() if p["trade_id"].startswith("spy-gamma-")]
    closed_count = 0

    ET = ZoneInfo("America/New_York")
    now_et = datetime.now(ET)
    force_close_time = now_et.hour == 15 and now_et.minute >= 45

    for pos in open_positions:
        trade_id = pos["trade_id"]
        contract_symbol = pos["contract_symbol"]
        entry_premium = pos["entry_premium"]
        contracts = pos["contracts"]

        try:
            current_premium = get_live_bid_price(contract_symbol)
        except Exception as exc:
            print("  Could not fetch premium for " + contract_symbol + ": " + str(exc))
            continue

        pct_change = (current_premium - entry_premium) / entry_premium if entry_premium > 0 else 0

        # Determine which tranche this position belongs to from its trade_id
        # (format: "spy-gamma-{A|B|RUNNER}-{order_id}").
        _tranche = "RUNNER"
        _id_parts = trade_id.split("-")
        if len(_id_parts) > 2 and _id_parts[2] in ("A", "B", "C", "RUNNER"):
            _tranche = _id_parts[2]

        exit_reason = None
        _own_stop_loss_pct = pos.get("stop_loss_pct", STOP_LOSS_PCT)
        _own_take_profit_pct = pos.get("take_profit_pct", TAKE_PROFIT_PCT)

        if pct_change <= -_own_stop_loss_pct:
            exit_reason = "stop_loss"
        elif _tranche == "RUNNER":
            # Looser reversal_guard: wait for 50%+ profit (vs the main
            # bot's 40%) before checking for a sustained reversal, since
            # this tranche is meant to run further before protecting gains.
            if pct_change >= 0.50:
                try:
                    from datetime import timedelta as _timedelta
                    import backtest_engine as _be
                    _now = datetime.now(timezone.utc)
                    _stock_bars = _be.get_historical_bars(pos.get("ticker", "SPY"), _now - _timedelta(hours=1), _now)
                    if len(_stock_bars) >= 7:
                        _closes = [float(b.close) for b in _stock_bars[-7:]]
                        _last_two = _closes[-2:]
                        _ma_before = sum(_closes[-7:-2]) / 5
                        _opt_type = pos["option_type"]
                        if _opt_type == "call" and all(c < _ma_before for c in _last_two):
                            exit_reason = "reversal_guard"
                        elif _opt_type == "put" and all(c > _ma_before for c in _last_two):
                            exit_reason = "reversal_guard"
                except Exception:
                    pass
        elif pct_change >= _own_take_profit_pct:
            exit_reason = "take_profit"

        if exit_reason is None and force_close_time:
            exit_reason = "day_trade_close"

        print("  " + contract_symbol + ": entry=$" + str(entry_premium) + " current=$" + str(round(current_premium, 2)) + " (" + str(round(pct_change*100, 1)) + "%) -- " + (exit_reason if exit_reason else "holding"))

        if exit_reason is None:
            continue

        if spy_gamma_daytrader.SPY_GAMMA_SHADOW_MODE:
            print("  SHADOW MODE -- would close " + contract_symbol + ": " + exit_reason)
            continue

        try:
            order_request = OptMarketOrderRequest(
                symbol=contract_symbol, qty=contracts, side=OptOrderSide.SELL, time_in_force=OptTimeInForce.DAY,
            )
            sell_order = _trading_client.submit_order(order_request)

            real_exit_premium = current_premium
            for _ in range(10):
                time.sleep(1)
                try:
                    refreshed = _trading_client.get_order_by_id(sell_order.id)
                    if refreshed.filled_avg_price:
                        real_exit_premium = float(refreshed.filled_avg_price)
                        break
                except Exception:
                    continue

            pnl_dollars = (real_exit_premium - entry_premium) * contracts * 100
            pnl_pct = (real_exit_premium - entry_premium) / entry_premium * 100 if entry_premium > 0 else 0

            options_trade_log.log_exit(trade_id, {
                "exit_date": datetime.now(timezone.utc).date().isoformat(),
                "exit_timestamp": datetime.now(timezone.utc).isoformat(),
                "exit_premium": real_exit_premium,
                "pnl_dollars": pnl_dollars,
                "pnl_pct": pnl_pct,
                "exit_reason": exit_reason,
            })
            closed_count += 1
            print("  Closed " + contract_symbol + ": " + exit_reason + ", P&L $" + str(round(pnl_dollars, 2)))

            try:
                _review_data = {
                    "ticker": pos.get("ticker", "SPY"),
                    "contract_symbol": contract_symbol,
                    "option_type": pos["option_type"],
                    "entry_premium": entry_premium,
                    "exit_premium": real_exit_premium,
                    "contracts": contracts,
                    "pnl_dollars": pnl_dollars,
                    "pnl_pct": pnl_pct,
                    "exit_reason": exit_reason,
                    "entry_date": pos["entry_date"],
                    "expiry_date": pos["expiry_date"],
                    "strategy_note": "SPY gamma/charm day-trading bot, tranche: " + _tranche,
                }
                review_and_store_trade(trade_id, _review_data)
                print("  AI review generated for " + contract_symbol)
            except Exception as review_exc:
                print("  AI review failed (trade still closed correctly): " + str(review_exc))
        except Exception as exc:
            print("  Failed to close " + contract_symbol + ": " + str(exc))

    return closed_count


